class GuideI18n {
  static String currentLang(BuildContext ctx) =>
      ctx.read<LanguageService>().currentCode;

  static String catTitle(BuildContext ctx, String catId) =>
      _catTitles[currentLang(ctx)]?[catId] ??
      _catTitles['it']?[catId] ??
      catId;

  static String schedaTitle(BuildContext ctx, String id) =>
      _schedaTitles[currentLang(ctx)]?[id] ??
      _schedaTitles['it']?[id] ??
      id;

  static String schedaDesc(BuildContext ctx, String id) =>
      _schedaDescs[currentLang(ctx)]?[id] ??
      _schedaDescs['it']?[id] ??
      '';

  static String header(BuildContext ctx) =>
      _headers[currentLang(ctx)] ?? _headers['it']!;

  static String intro(BuildContext ctx) =>
      _intros[currentLang(ctx)] ?? _intros['it']!;

  static String schedeLabel(BuildContext ctx, int n) {
    final lang = currentLang(ctx);
    final tpl = _schedeLabels[lang] ?? _schedeLabels['it']!;
    return tpl.replaceAll('{n}', '$n');
  }
}

